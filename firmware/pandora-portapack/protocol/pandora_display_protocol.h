#ifndef PANDORA_DISPLAY_PROTOCOL_H
#define PANDORA_DISPLAY_PROTOCOL_H

#include <stdint.h>

/*
 * Read-only framebuffer transfer between the ESP32-MDK module and its
 * PortaPack standalone app. This protocol has no input or radio commands.
 */
#define PANDORA_DISPLAY_META_COMMAND 0x7F20u
#define PANDORA_DISPLAY_FRAME_COMMAND 0x7F21u

#define PANDORA_DISPLAY_FRAME_BYTES 1472u
#define PANDORA_DISPLAY_RESPONSE_BYTES 128u
#define PANDORA_DISPLAY_RESPONSE_HEADER_BYTES 4u
#define PANDORA_DISPLAY_CHUNK_BYTES \
    (PANDORA_DISPLAY_RESPONSE_BYTES - PANDORA_DISPLAY_RESPONSE_HEADER_BYTES)

#define PANDORA_DISPLAY_COLUMNS 92u
#define PANDORA_DISPLAY_VISIBLE_COLUMNS 88u
#define PANDORA_DISPLAY_PAGES 16u
#define PANDORA_DISPLAY_ROWS (PANDORA_DISPLAY_PAGES * 4u)

#endif
